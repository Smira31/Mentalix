import { UNSAFE_INSIGHT_PATTERNS } from './descriptiveInsights'

// ── MXL-AI-REFRAME-001: safety-слой для кнопки «Обсудить с AI» на
// сохранённой записи чек-ина/дневника (History.jsx) ──
//
// Переиспользует regex-паттерны фильтра MXL-009 (descriptiveInsights.js) —
// единый источник того, что считается диагностической/причинной/
// терапевтической формулировкой в проекте. Не отбрасывает ответ AI (это
// диалог, а не список инсайтов — молча скрыть реплику было бы хуже, чем
// показать её с явной оговоркой), а помечает подозрительный ответ коротким
// текстовым примечанием — тот же принцип «не доверять сырому выводу
// модели», адаптированный к формату чата.

export const AI_REFRAME_LEAD_MESSAGE = {
  role: 'assistant',
  content:
    'Помогу посмотреть на это ещё раз вместе с тобой. Учти: я не ставлю диагнозы и не заменяю специалиста — если тяжело, важно поговорить с человеком, которому доверяешь, или обратиться за профессиональной помощью.',
}

const SAFETY_NOTE =
  '\n\n— Это не диагноз и не замена специалиста. Если тяжело, важно поговорить с человеком, которому доверяешь, или обратиться за профессиональной помощью.'

export function containsUnsafeLanguage(text) {
  if (typeof text !== 'string' || !text.trim()) return false

  return UNSAFE_INSIGHT_PATTERNS.some(pattern => pattern.test(text))
}

/*
 * Возвращает текст ответа AI, дополненный оговоркой, если он задел
 * диагностический/причинный/терапевтический паттерн. Не переписывает и не
 * обрезает сам ответ модели — только добавляет примечание.
 */
export function withSafetyNote(content) {
  if (!containsUnsafeLanguage(content)) return content

  return `${content}${SAFETY_NOTE}`
}
