/*
 * MXL-PROMPT-ROTATION-001: единый источник правды для трёх наборов
 * ротируемых текстов, которые раньше были захардкожены по одному варианту
 * прямо в CheckIn.jsx/personas.js.
 *
 * День для ротации берётся по МСК через Intl.DateTimeFormat, не через
 * голый new Date() (локальное время устройства) — тот же принцип, что и
 * у backend/timeutils.py::get_today() (ZoneInfo('Europe/Moscow')),
 * зафиксированный после MXL-TIMEZONE-CHECKIN-001. Здесь это не бэкенд, но
 * граница дня не должна расходиться с тем, что уже используется в проекте
 * для чек-ина/серий — иначе текст сменится в другой момент, чем сам день.
 */

function mskDayOfYear() {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Moscow',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(new Date())

  const map = Object.fromEntries(parts.map(({ type, value }) => [type, value]))
  const year = Number(map.year)
  const month = Number(map.month)
  const day = Number(map.day)

  const startOfYear = Date.UTC(year, 0, 1)
  const current = Date.UTC(year, month - 1, day)

  return Math.round((current - startOfYear) / 86400000) + 1
}

/*
 * Общая функция ротации: детерминированный выбор по дню — один и тот же
 * элемент весь календарный день по МСК, у всех пользователей одинаковый.
 * offset позволяет получить второй, отличный от первого, элемент того же
 * набора на тот же день (нужно personas.js — там раньше показывалось два
 * стартера одновременно, не один).
 */
export function pickByDay(list, offset = 0) {
  return list[(mskDayOfYear() + offset) % list.length]
}

